#!/usr/bin/env python3
"""Build 24A446 arm64e libViolinHidInput.late.a with strict 207-slot PAC alignment.

Generates OriginalHidDeviceABI.h and BTI/B original kext stubs from the pinned
24A446 kernelcache + original-classes.json, compiles ViolinHidInput.cpp,
rewrites & audits all 207 arm64e PAC vtable slot diversities and virtual
call-site movk immediates, removes __DATA,__mod_init_func for deferred
metaclass registration, and emits libViolinHidInput.late.a + build-report.json.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess
import sys

NAMED_SLOTS = {
    171: ("newTransportString", "virtual OSString *newTransportString() const;"),
    173: ("newProductString", "virtual OSString *newProductString() const;"),
    180: ("newReportDescriptor", "virtual IOReturn newReportDescriptor(IOMemoryDescriptor **) const = 0;"),
    181: ("handleReport", "virtual IOReturn handleReport(IOMemoryDescriptor *, unsigned, IOOptionBits);"),
}

BASE_OVERRIDES = [
    "IOReturn Dispatch(IORPC) override;",
    "void free() override;",
    "bool init(OSDictionary *properties = nullptr) override;",
    "bool setProperty(const OSSymbol *, OSObject *) override;",
    "bool willTerminate(IOService *, IOOptionBits) override;",
    "IOReturn configureReport(IOReportChannelList *, IOReportConfigureAction, void *, void *) override;",
    "IOReturn updateReport(IOReportChannelList *, IOReportUpdateAction, void *, void *) override;",
    "bool start(IOService *) override;",
    "void stop(IOService *) override;",
    "bool handleOpen(IOService *, IOOptionBits, void *) override;",
    "void handleClose(IOService *, IOOptionBits) override;",
    "bool handleIsOpen(const IOService *) const override;",
    "bool matchPropertyTable(OSDictionary *, SInt32 *) override;",
    "IOReturn message(UInt32, IOService *, void *) override;",
    "IOReturn newUserClient(task_t, void *, UInt32, OSDictionary *, IOUserClient **) override;",
]


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def parse_macho_object(data: bytes):
    magic, cpu, cpusub, filetype, ncmds, sizeofcmds, flags, _ = struct.unpack_from("<8I", data, 0)
    if magic != 0xFEEDFACF or cpu != 0x0100000C or filetype != 1:
        raise SystemExit(f"Not an arm64/arm64e MH_OBJECT (magic={magic:#x} cpu={cpu:#x} type={filetype})")
    sections, symbols = [], []
    pos = 32
    for _ in range(ncmds):
        cmd, cmdsize = struct.unpack_from("<2I", data, pos)
        if cmd == 0x19:
            nsects = struct.unpack_from("<I", data, pos + 64)[0]
            spos = pos + 72
            for _ in range(nsects):
                sname = data[spos:spos + 16].split(b"\0", 1)[0].decode()
                segname = data[spos + 16:spos + 32].split(b"\0", 1)[0].decode()
                addr, size, offset, align, reloff, nreloc, sflags = struct.unpack_from("<2Q5I", data, spos + 32)
                sections.append({
                    "name": sname, "seg": segname, "addr": addr, "size": size,
                    "offset": offset, "reloff": reloff, "nreloc": nreloc, "flags": sflags,
                })
                spos += 80
        elif cmd == 0x2:
            symoff, nsyms, stroff, strsize = struct.unpack_from("<4I", data, pos + 8)
            for idx in range(nsyms):
                strx, ntype, nsect, ndesc, nval = struct.unpack_from("<IBBHQ", data, symoff + idx * 16)
                end = data.index(b"\0", stroff + strx)
                name = data[stroff + strx:end].decode()
                symbols.append({"index": idx, "name": name, "type": ntype, "sect": nsect, "desc": ndesc, "val": nval})
        pos += cmdsize
    return sections, symbols


def generate_abi_header(cls_info: dict) -> str:
    size = int(cls_info["size"], 16)
    lines = [
        "// SPDX-License-Identifier: BSD-2-Clause-Patent",
        "// Auto-generated by build-violin-hid-input.py from pinned 24A446 kernelcache.",
        "#pragma once",
        "#include <IOKit/IOMemoryDescriptor.h>",
        "#include <IOKit/IOService.h>",
        "#include <IOKit/IOUserClient.h>",
        "#include <libkern/c++/OSDictionary.h>",
        "#include <libkern/c++/OSString.h>",
        "",
        "class IOHIDDevice : public IOService {",
        "    OSDeclareAbstractStructors(IOHIDDevice)",
        f"    unsigned char originalPrivate[{size:#x} - sizeof(IOService)];",
        "public:",
        "    using IOService::setProperty;",
    ]
    for decl in BASE_OVERRIDES:
        lines.append(f"    {decl}")
    for slot in range(168, cls_info["slots"]):
        if slot in NAMED_SLOTS:
            lines.append(f"    {NAMED_SLOTS[slot][1]}")
        else:
            lines.append(f"    virtual void opaque{slot}();")
    lines.extend([
        "};",
        f'static_assert(sizeof(IOHIDDevice) == {size:#x}, "24A446 IOHIDDevice size");',
        "",
    ])
    return "\n".join(lines)


def patch_and_audit_pac(raw_obj: bytes, orig_divs: list[int], expected_slots: int):
    buf = bytearray(raw_obj)
    sections, symbols = parse_macho_object(raw_obj)
    sym_by_name = {s["name"]: s for s in symbols if s["sect"] != 0}
    vt_sym = sym_by_name.get("__ZTV14ViolinHidInput")
    if vt_sym is None:
        raise SystemExit("Missing __ZTV14ViolinHidInput in compiled object")
    vt_sec = sections[vt_sym["sect"] - 1]
    vt_base_off = vt_sym["val"] - vt_sec["addr"]

    slot_relocs = {}
    for i in range(vt_sec["nreloc"]):
        r_addr, r_info = struct.unpack_from("<2I", raw_obj, vt_sec["reloff"] + i * 8)
        r_sym = r_info & 0xFFFFFF
        r_pcrel = (r_info >> 24) & 1
        r_len = (r_info >> 25) & 3
        r_ext = (r_info >> 27) & 1
        r_type = (r_info >> 28) & 0xF
        if vt_base_off + 16 <= r_addr < vt_base_off + 16 + (expected_slots + 2) * 8:
            if (r_addr - (vt_base_off + 16)) % 8 != 0:
                raise SystemExit(f"Unaligned vtable reloc at {r_addr:#x}")
            slot = (r_addr - (vt_base_off + 16)) // 8
            if r_type != 11 or r_ext != 1 or r_len != 3 or r_pcrel != 0:
                raise SystemExit(f"Slot {slot}: expected ARM64_RELOC_AUTHENTICATED_POINTER, got type={r_type}")
            slot_relocs[slot] = (r_addr, symbols[r_sym]["name"])

    if len(slot_relocs) != expected_slots or set(slot_relocs) != set(range(expected_slots)):
        raise SystemExit(f"Expected exact {expected_slots} vtable slots, got {len(slot_relocs)}")

    synth_divs, base_mismatches, compiled_slot_syms = {}, [], []
    rewritten_slots = 0
    for slot in range(expected_slots):
        r_addr, target_name = slot_relocs[slot]
        compiled_slot_syms.append(target_name)
        file_pos = vt_sec["offset"] + r_addr
        word = struct.unpack_from("<Q", buf, file_pos)[0]
        auth = (word >> 63) & 1
        key = (word >> 49) & 3
        addr_div = (word >> 48) & 1
        div = (word >> 32) & 0xFFFF
        addend = word & 0xFFFFFFFF
        if (auth, key, addr_div, addend) != (1, 0, 1, 0):
            raise SystemExit(f"Slot {slot} ({target_name}): unexpected auth ptr word={word:#018x}")
        synth_divs[slot] = div
        if slot < 168:
            if div != orig_divs[slot]:
                base_mismatches.append((slot, target_name, hex(div), hex(orig_divs[slot])))
        else:
            if div != orig_divs[slot]:
                new_word = (word & ~(0xFFFF << 32)) | (orig_divs[slot] << 32)
                struct.pack_into("<Q", buf, file_pos, new_word)
                rewritten_slots += 1
    if base_mismatches:
        raise SystemExit(f"IOService 0..167 PAC diversity mismatch: {base_mismatches[:10]}")

    text_sec = next(s for s in sections if s["seg"] == "__TEXT" and s["name"] == "__text")
    text_base = text_sec["offset"]
    words = list(struct.unpack_from(f"<{text_sec['size'] // 4}I", buf, text_base))
    text_syms = sorted(
        [(s["val"] - text_sec["addr"], s["name"]) for s in symbols if s["sect"] == sections.index(text_sec) + 1 and s["name"]],
        key=lambda x: x[0],
    )

    def sym_for_off(byte_off: int) -> str:
        cur = "<unknown>"
        for soff, sname in text_syms:
            if soff <= byte_off:
                cur = sname
            else:
                break
        return cur

    text_reloc_syms = {}
    for i in range(text_sec["nreloc"]):
        r_addr, r_info = struct.unpack_from("<2I", raw_obj, text_sec["reloff"] + i * 8)
        if (r_info >> 27) & 1:
            text_reloc_syms[r_addr] = symbols[r_info & 0xFFFFFF]["name"]

    patched_callsites = []
    audited_base_callsites = 0
    for i, w in enumerate(words):
        is_blraa = (w & 0xFFFFFC00) == 0xD73F0800
        is_braa = (w & 0xFFFFFC00) == 0xD71F0800
        if not (is_blraa or is_braa):
            continue
        # Skip violin_edge::call / dispatch dynamic calls (non-vtable movk: they use ptrauth_auth_and_resign + blr/br, not blraa)
        rn_target = (w >> 5) & 0x1F
        rm_mod = w & 0x1F
        movk_idx, movk_div = None, None
        type_disc_imm = None
        for j in range(i - 1, max(-1, i - 16), -1):
            pw = words[j]
            if (pw & 0xFFE00000) == 0xF2E00000 and (pw & 0x1F) == rm_mod:
                movk_idx = j
                movk_div = (pw >> 5) & 0xFFFF
                break
            if (pw & 0xFFE00000) == 0xD2800000 and (pw & 0x1F) == rm_mod:
                type_disc_imm = (pw >> 5) & 0xFFFF
                break
        if movk_idx is None:
            if type_disc_imm is not None and "violin_edge" in sym_for_off(i * 4):
                audited_base_callsites += 1
                continue
            raise SystemExit(f"Unrecognized blraa/braa at {sym_for_off(i*4)}+{i*4:#x}")

        slot_byte_off, add_idx = None, None
        addr_reg = rm_mod
        for j in range(movk_idx - 1, max(-1, movk_idx - 12), -1):
            pw = words[j]
            if (pw & 0xFFE0FFE0) == 0xAA0003E0 and (pw & 0x1F) == addr_reg:
                addr_reg = (pw >> 16) & 0x1F
                break
        for j in range(movk_idx - 1, max(-1, i - 24), -1):
            pw = words[j]
            if (pw & 0xFFE00C00) == 0xF8400C00 and ((pw >> 5) & 0x1F) == addr_reg:
                imm9 = (pw >> 12) & 0x1FF
                if imm9 & 0x100:
                    imm9 -= 0x200
                slot_byte_off, add_idx = imm9, j
                break
            if (pw & 0xFFC00000) == 0x91000000 and (pw & 0x1F) == addr_reg:
                slot_byte_off, add_idx = (pw >> 10) & 0xFFF, j
                break
            if (pw & 0xFFE0FC00) == 0x8B000000 and (pw & 0x1F) == addr_reg:
                rm_off = (pw >> 16) & 0x1F
                for k in range(j - 1, max(-1, j - 8), -1):
                    kw = words[k]
                    if ((kw & 0x7FE00000) == 0x52800000) and (kw & 0x1F) == rm_off:
                        slot_byte_off, add_idx = (kw >> 5) & 0xFFFF, j
                        break
                if slot_byte_off is not None:
                    break
            if (pw & 0xFFC00000) == 0xF9400000 and (pw & 0x1F) == rn_target:
                imm12 = (pw >> 10) & 0xFFF
                if imm12 != 0:
                    slot_byte_off, add_idx = imm12 * 8, j
                    break

        if slot_byte_off is None or slot_byte_off < 0 or slot_byte_off % 8 != 0:
            raise SystemExit(f"Cannot determine slot offset at {sym_for_off(i*4)}+{i*4:#x}")

        ztv_super = None
        for k in range(add_idx - 1, max(-1, add_idx - 6), -1):
            rsym = text_reloc_syms.get(k * 4)
            if rsym and rsym.startswith("__ZTV"):
                ztv_super = rsym
                break
        if ztv_super is not None:
            slot = (slot_byte_off - 16) // 8
            if ztv_super == "__ZTV11IOHIDDevice" and slot >= 168:
                if movk_div != synth_divs[slot]:
                    raise SystemExit(f"Super slot {slot} div mismatch: {movk_div:#x} != {synth_divs[slot]:#x}")
                new_div = orig_divs[slot]
                if new_div != movk_div:
                    new_ins = (words[movk_idx] & ~(0xFFFF << 5)) | (new_div << 5)
                    words[movk_idx] = new_ins
                    struct.pack_into("<I", buf, text_base + movk_idx * 4, new_ins)
                patched_callsites.append({"func": sym_for_off(i*4), "slot": slot, "old": hex(movk_div), "new": hex(new_div)})
            else:
                audited_base_callsites += 1
            continue

        slot = slot_byte_off // 8
        if slot >= 168:
            if slot >= expected_slots:
                raise SystemExit(f"Out-of-range vtable slot {slot} at {sym_for_off(i*4)}+{i*4:#x}")
            if movk_div != synth_divs[slot]:
                raise SystemExit(f"Callsite slot {slot} div mismatch: {movk_div:#x} != {synth_divs[slot]:#x}")
            new_div = orig_divs[slot]
            if new_div != movk_div:
                new_ins = (words[movk_idx] & ~(0xFFFF << 5)) | (new_div << 5)
                words[movk_idx] = new_ins
                struct.pack_into("<I", buf, text_base + movk_idx * 4, new_ins)
            patched_callsites.append({"func": sym_for_off(i*4), "slot": slot, "old": hex(movk_div), "new": hex(new_div)})
        else:
            audited_base_callsites += 1

    return bytes(buf), compiled_slot_syms, {
        "vtable_slots_total": expected_slots,
        "vtable_base_0_167_mismatches": 0,
        "vtable_subclass_168_206_rewritten": rewritten_slots,
        "callsites_base_lt_168_audited": audited_base_callsites,
        "callsites_subclass_ge_168_patched": patched_callsites,
    }


def main():
    violin_root = Path(__file__).resolve().parents[1]
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tree", type=Path, default=Path("/opt/unixnu-out/stage7j-qemu-launchd/tree"))
    ap.add_argument("--unixnu", type=Path, default=violin_root.parent / "UniXNU")
    ap.add_argument("--kernelcache", type=Path, default=Path("/opt/unixnu-out/ipsw/24A446/kernelcache.decompressed"))
    ap.add_argument("--source", type=Path, default=violin_root / "drivers/ViolinHidInput/ViolinHidInput.cpp")
    ap.add_argument("--out-dir", type=Path, default=Path("/opt/unixnu-out/stage8c-touch/violin-hid-input"))
    ap.add_argument("--collection-slide", type=lambda s: int(s, 0), default=0x1F000000000)
    args = ap.parse_args()

    tree = args.tree.resolve()
    unixnu = args.unixnu.resolve()
    out = args.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)

    sys.path.insert(0, str(unixnu / "kits/XnuPrelink"))
    sys.path.insert(0, str(unixnu / "scripts"))
    from kc_image import Image as KCImage
    from kernel_target import ARCH, TRIPLE, check_object

    if ARCH != "arm64e":
        raise SystemExit(f"Expected UNIXNU_XNU_ARCH=arm64e, got {ARCH!r}")

    abi = json.loads((unixnu / "profiles/os/ipados-27.0.1-24A446/abi/original-classes.json").read_text())
    kc_bytes = args.kernelcache.read_bytes()
    if sha256_bytes(kc_bytes) != abi["kernelcache_sha256"]:
        raise SystemExit("kernelcache SHA-256 mismatch")

    kc = KCImage(kc_bytes)
    fixups = kc.fixups()
    cls = abi["classes"]["IOHIDDevice"]
    vtable_va = int(cls["vtable"], 16)
    vptr_va = vtable_va + 16
    slots = cls["slots"]
    pure_va = int(abi["classes"]["IOMobileFramebufferLegacy"]["pure_virtual"], 16)

    orig_vas, orig_divs, pure_slots = [], [], []
    for s in range(slots):
        t, auth, key, div, ad = fixups[vptr_va + s * 8]
        if (auth, key, ad) != (1, 0, 1):
            raise SystemExit(f"IOHIDDevice slot {s} unexpected auth tuple {(auth, key, ad)}")
        orig_vas.append(t)
        orig_divs.append(div)
        if t == pure_va:
            pure_slots.append(s)
    if pure_slots != [180]:
        raise SystemExit(f"Unexpected IOHIDDevice pure slots: {pure_slots}")

    (out / "OriginalHidDeviceABI.h").write_text(generate_abi_header(cls))

    recipe_path = tree / "build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json"
    record = json.loads(recipe_path.read_text().strip().rstrip(","))
    raw_obj = out / "ViolinHidInput.raw.o"

    cmd = []
    args_list = record["arguments"]
    i = 0
    while i < len(args_list):
        v = args_list[i]
        if v == record["file"]:
            cmd.append(str(args.source))
        elif v == "-o":
            cmd.extend(["-o", str(raw_obj)])
            i += 1
        elif v in ("-MF", "-MT", "-MQ", "-MJ"):
            i += 1
        elif v in ("-MD", "-MMD", "-MP"):
            pass
        elif v == "-Xclang" and i + 1 < len(args_list) and args_list[i + 1].startswith("-W"):
            i += 1
        elif not v.startswith("-W"):
            cmd.append(v)
        i += 1
    cmd.extend([
        "-Wall", "-Wextra", "-Werror",
        "-Wno-unused-parameter", "-Wno-c99-designator", "-Wno-reorder-init-list",
        "-Wno-deprecated-enum-enum-conversion", "-Wno-unnecessary-virtual-specifier",
        "-Wno-missing-designated-field-initializers", "-Wno-unused-but-set-global",
        "-I", str(out),
        "-I", str(tree / ".cache/xnu-work/osfmk"),
    ])
    res = subprocess.run(cmd, cwd=record["directory"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    (out / "compile.log").write_text(res.stdout)
    if res.returncode != 0:
        raise SystemExit(f"ViolinHidInput.cpp compile failed:\n{res.stdout[-4000:]}")
    check_object(raw_obj.read_bytes(), raw_obj.name)

    pac_bytes, compiled_slot_syms, pac_audit = patch_and_audit_pac(raw_obj.read_bytes(), orig_divs, slots)
    pac_obj = out / "ViolinHidInput.pac.o"
    pac_obj.write_bytes(pac_bytes)
    check_object(pac_bytes, pac_obj.name)

    _, pac_syms = parse_macho_object(pac_bytes)
    undefined = {s["name"] for s in pac_syms if s["type"] == 1}

    code_bindings = {
        "__ZN11IOHIDDeviceC2EPK11OSMetaClass": int(cls["constructor"], 16),
        "__ZN11IOHIDDeviceD2Ev": int(cls["destructor"], 16),
        "__ZN11IOHIDDevice4freeEv": orig_vas[14],
        "__ZN11IOHIDDevice5startEP9IOService": orig_vas[86],
        "__ZN11IOHIDDevice4stopEP9IOService": orig_vas[87],
        "__ZN11IOHIDDevice12handleReportEP18IOMemoryDescriptorjj": orig_vas[181],
    }
    data_bindings = {
        "__ZN11IOHIDDevice10gMetaClassE": int(cls["meta_class"], 16),
        "__ZTV11IOHIDDevice": vtable_va,
    }
    for s, sym_name in enumerate(compiled_slot_syms):
        if "11IOHIDDevice" in sym_name:
            if orig_vas[s] == pure_va:
                raise SystemExit(f"Pure slot {s} ({sym_name}) not overridden!")
            code_bindings[sym_name] = orig_vas[s]

    hid_undef = {n for n in undefined if "11IOHIDDevice" in n}
    missing = hid_undef - set(code_bindings) - set(data_bindings)
    if missing:
        raise SystemExit(f"Unbound IOHIDDevice symbols: {sorted(missing)}")

    slide = args.collection_slide
    stubs_lines = [".text", ".p2align 2"]
    addrs_lines = []
    for sym_name, orig_va in sorted(code_bindings.items()):
        if sym_name not in undefined:
            continue
        slid = orig_va + slide
        addrs_lines.append(f".globl {sym_name}.original")
        addrs_lines.append(f".set {sym_name}.original, {slid:#x}")
        stubs_lines.append(f".globl {sym_name}")
        stubs_lines.append(f"{sym_name}:")
        stubs_lines.append("    bti c")
        stubs_lines.append(f"    b {sym_name}.original")
    for sym_name, orig_va in sorted(data_bindings.items()):
        if sym_name not in undefined:
            continue
        slid = orig_va + slide
        addrs_lines.append(f".globl {sym_name}")
        addrs_lines.append(f".set {sym_name}, {slid:#x}")

    stubs_s = out / "ViolinHidInput24A446Stubs.S"
    addrs_s = out / "ViolinHidInput24A446Addrs.S"
    stubs_o = out / "ViolinHidInput24A446Stubs.o"
    addrs_o = out / "ViolinHidInput24A446Addrs.o"
    stubs_s.write_text("\n".join(stubs_lines) + "\n")
    addrs_s.write_text("\n".join(addrs_lines) + "\n")

    sdk = subprocess.check_output(["xcrun", "--sdk", "iphoneos", "--show-sdk-path"], text=True).strip()
    subprocess.run(["xcrun", "clang", "-target", TRIPLE, "-isysroot", sdk, "-c", str(stubs_s), "-o", str(stubs_o)], check=True)
    subprocess.run(["xcrun", "clang", "-target", TRIPLE, "-isysroot", sdk, "-c", str(addrs_s), "-o", str(addrs_o)], check=True)
    check_object(stubs_o.read_bytes(), stubs_o.name)

    late_obj = out / "ViolinHidInput.late.o"
    objcopy = "llvm-objcopy-21" if subprocess.run(["which", "llvm-objcopy-21"], capture_output=True).returncode == 0 else "llvm-objcopy"
    init_sym = next((s for s in pac_syms if "GLOBAL__sub_I_ViolinHidInput" in s["name"]), None)
    if init_sym is None:
        raise SystemExit("Could not locate __GLOBAL__sub_I_ViolinHidInput initializer symbol")
    subprocess.run([
        objcopy,
        "--remove-section=__DATA,__mod_init_func",
        f"--globalize-symbol={init_sym['name']}",
        str(pac_obj),
        str(late_obj),
    ], check=True)
    late_bytes = late_obj.read_bytes()
    check_object(late_bytes, late_obj.name)
    late_secs, late_syms = parse_macho_object(late_bytes)
    if any(s["name"] == "__mod_init_func" for s in late_secs):
        raise SystemExit("__DATA,__mod_init_func was NOT removed from ViolinHidInput.late.o")
    g_sym = next((s for s in late_syms if s["name"] == init_sym["name"]), None)
    if g_sym is None or not (g_sym["type"] & 1):
        raise SystemExit(f"Initializer {init_sym['name']} is still local after globalize")

    out_a = out / "libViolinHidInput.late.a"
    out_a.unlink(missing_ok=True)
    subprocess.run(["xcrun", "ar", "rcs", str(out_a), str(late_obj), str(stubs_o), str(addrs_o)], check=True)
    subprocess.run(["xcrun", "ranlib", str(out_a)], check=True)

    report = {
        "status": "PASS",
        "archive": str(out_a),
        "pac_audit": pac_audit,
        "code_bindings_count": len([k for k in code_bindings if k in undefined]),
        "data_bindings_count": len([k for k in data_bindings if k in undefined]),
    }
